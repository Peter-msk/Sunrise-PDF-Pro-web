import {canRecoverFile,recoveryEngine,planConversion,planBulkRecovery,localFailureAdvice} from '../browser-local/src/conversion-recovery.mjs';
const uuid=n=>'00000000-0000-4000-8000-'+n.toString(16).padStart(12,'0');
test('trace observer correlates DEV68 operations and reports only accepted trace IDs',async()=>{
 const requests=[],ids=[];let n=100,ok=true;
 const window={fetch:async(input,init)=>{if(input==='/api/public/trace-dev4')requests.push(JSON.parse(init.body));return {ok};}};
 const document={readyState:'complete',querySelector:()=>({append:p=>ids.push(p.textContent)}),getElementById:()=>null,createElement:()=>({style:{}})};
 const location={href:'https://example.test/local/',origin:'https://example.test'};
 const res=await traceDev4Route(new Request('https://example.test/trace-dev4-client.js'),{});
 assert.equal(res.status,200);
 vm.runInNewContext(await res.text(),{window,document,location,URL,crypto:{randomUUID:()=>uuid(n++)},navigator:{userAgent:'Chrome/100'},performance:{now:()=>1234},MutationObserver:class{observe(){}}});
 const session_id=uuid(1),op=uuid(2),other=uuid(3);
 const emit=async(kind,extra={})=>{await window.fetch('/api/public/telemetry',{method:'POST',body:JSON.stringify({kind,session_id,operation_id:op,feature:'hwp',stage:'render',...extra})});await Promise.resolve();};
 await emit('convert_start');await emit('convert_failure',{operation_id:other,error_code:'PDF_STREAM_TIMEOUT'});
 assert.equal(requests.length,0);
 await emit('convert_failure',{error_code:'FONT_FAMILY_OR_VARIANT_UNAVAILABLE'});
 assert.equal(requests[0].operation_id,op);assert.equal(requests[0].session_id,session_id);
 assert.equal(requests[0].phase,'fonts');assert.equal(requests[0].module,'pdf_fonts');assert.equal(ids.length,1);
 await emit('convert_start',{operation_id:other});ok=false;
 await emit('convert_failure',{operation_id:other,error_code:'PDF_STREAM_TIMEOUT',stage:'unknown'});
 assert.equal(requests[1].phase,'pdf');assert.equal(ids.length,1);
 ok=true;await emit('convert_start');await emit('convert_success');await emit('convert_failure',{error_code:'CONVERSION_FAILED'});
 assert.equal(requests.length,2);
 await emit('convert_start',{operation_id:undefined});await emit('convert_failure',{operation_id:undefined,error_code:'SVG_FILTER_EFFECT_UNSUPPORTED'});
 assert.equal(requests.length,3);assert.equal(requests[2].phase,'render');assert.notEqual(requests[2].operation_id,op);
});
test('recovery keeps professional default and requires explicit per-file or bulk choice',()=>{
 const item=(error,engine='professional',name='sample.hwp',state='failed')=>({state,error,lastEngine:engine,file:{name}});
 const family=item('FONT_FAMILY_OR_VARIANT_UNAVAILABLE'),svg=item('SVG_FILTER_EFFECT_UNSUPPORTED'),hybrid=item('SVG_FILTER_EFFECT_UNSUPPORTED','hybrid-filter'),timeout=item('PDF_STREAM_TIMEOUT'),done=item('FONT_FAMILY_OR_VARIANT_UNAVAILABLE','professional','sample.hwp','done'),xlsx=item('FONT_FAMILY_OR_VARIANT_UNAVAILABLE','professional','sample.xlsx'),ready=item('FONT_FAMILY_OR_VARIANT_UNAVAILABLE','professional','sample.hwp','ready');
 assert.equal(canRecoverFile(family),false);assert.equal(recoveryEngine(family),null);
 assert.equal(recoveryEngine(svg),'hybrid-filter');assert.equal(recoveryEngine(hybrid),'compat-raster');
 assert.equal(recoveryEngine(timeout),'compat-raster');assert.ok(!canRecoverFile(xlsx)&&!canRecoverFile(done));
 assert.equal(planConversion([family,ready],'professional').engine,'professional');
 assert.equal(planBulkRecovery([family,svg,done,xlsx,ready]).pending.length,1);
 assert.match(localFailureAdvice(family.error),/TTF\/OTF/);assert.match(localFailureAdvice(family.error),/원본 모양을 보장하지 못하므로/);
 assert.match(localFailureAdvice(timeout.error),/불완전한 PDF/);
});
